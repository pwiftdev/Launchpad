/* Catalog reads only. The separate build script uses an in-memory development database. */
const { createHash } = require('node:crypto');
const sha = (value) => createHash('sha256').update(value).digest('hex');
function canonical(value) {
  if (Array.isArray(value)) return '[' + value.map(canonical).join(',') + ']';
  if (value && typeof value === 'object')
    return (
      '{' +
      Object.keys(value)
        .sort()
        .map((key) => JSON.stringify(key) + ':' + canonical(value[key]))
        .join(',') +
      '}'
    );
  return JSON.stringify(value);
}
/** Fold only whitespace outside SQL literals/quoted names; never change quoted semantics. */
function sql(value) {
  if (value === null) return null;
  let out = '',
    quote = null,
    space = false;
  for (let index = 0; index < value.length; index++) {
    const char = value[index];
    if (quote) {
      out += char;
      if (char === quote) {
        if (value[index + 1] === quote) out += value[++index];
        else quote = null;
      }
      continue;
    }
    if (char === "'" || char === '"') {
      if (space && out) out += ' ';
      space = false;
      quote = char;
      out += char;
    } else if (/\s/.test(char)) space = true;
    else {
      if (space && out) out += ' ';
      space = false;
      out += char;
    }
  }
  return out.trim();
}
function constraintsByMeaning(rows) {
  const unique = new Map();
  for (const row of rows) {
    const definition = sql(row.definition),
      name = row.type === 'c' ? `check:${sha(definition)}` : row.name,
      value = { ...row, name, definition };
    unique.set(`${row.table_name}.${name}`, value);
  }
  return [...unique.values()].sort(
    (a, b) => a.table_name.localeCompare(b.table_name) || a.name.localeCompare(b.name)
  );
}
async function readSchemaCatalog(client, scope) {
  const tables = (
    await client.query(
      `SELECT table_name FROM information_schema.tables WHERE table_schema='public' AND table_type='BASE TABLE' AND($1::text[] IS NULL OR table_name=ANY($1::text[])) ORDER BY table_name LIMIT 10001`,
      [scope?.tables ?? null]
    )
  ).rows.map((row) => row.table_name);
  const selected = scope?.tables ?? tables;
  const columns = (
    await client.query(
      `SELECT table_name,column_name,udt_name,is_nullable,column_default,character_maximum_length,numeric_precision,numeric_scale FROM information_schema.columns WHERE table_schema='public' AND table_name=ANY($1::text[]) ORDER BY table_name,ordinal_position LIMIT 10001`,
      [selected]
    )
  ).rows.map((row) => ({ ...row, column_default: sql(row.column_default) }));
  // PostgreSQL18 exposes NOT NULL in pg_constraint;15 does not. is_nullable above checks it on both.
  // Idempotent migrations can retain a named CHECK beside an older identical autogenerated CHECK.
  // Compare the exact invariant once, rather than requiring duplicate/name artifacts.
  const constraintRows = (
    await client.query(
      `SELECT r.relname AS table_name,c.conname AS name,c.contype AS type,c.convalidated AS validated,pg_get_constraintdef(c.oid,false) AS definition FROM pg_constraint c JOIN pg_class r ON r.oid=c.conrelid JOIN pg_namespace n ON n.oid=r.relnamespace WHERE n.nspname='public' AND c.contype<>'n' AND r.relname=ANY($1::text[]) ORDER BY r.relname,c.conname LIMIT 10001`,
      [selected]
    )
  ).rows;
  if (constraintRows.length > 10_000) throw new Error('Catalog capacity exceeded');
  const constraints = constraintsByMeaning(constraintRows);
  const indexes = (
    await client.query(
      `SELECT tablename AS table_name,indexname AS name,indexdef AS definition FROM pg_indexes WHERE schemaname='public' AND tablename=ANY($1::text[]) ORDER BY tablename,indexname LIMIT 10001`,
      [selected]
    )
  ).rows.map((row) => ({ ...row, definition: sql(row.definition) }));
  const triggers = (
    await client.query(
      `SELECT r.relname AS table_name,t.tgname AS name,t.tgenabled AS enabled,p.proname AS function_name,pg_get_triggerdef(t.oid,false) AS definition FROM pg_trigger t JOIN pg_class r ON r.oid=t.tgrelid JOIN pg_namespace n ON n.oid=r.relnamespace JOIN pg_proc p ON p.oid=t.tgfoid WHERE n.nspname='public' AND NOT t.tgisinternal AND r.relname=ANY($1::text[]) ORDER BY r.relname,t.tgname LIMIT 10001`,
      [selected]
    )
  ).rows.map((row) => ({ ...row, definition: sql(row.definition) }));
  const names = scope?.functions ?? [...new Set(triggers.map((row) => row.function_name))];
  // Hash bodies inside PostgreSQL; raw stored function contents never leave the server.
  const functions = (
    await client.query(
      `SELECT p.proname AS name,pg_get_function_identity_arguments(p.oid) AS arguments,l.lanname AS language,p.prosecdef AS security_definer,p.provolatile AS volatility,p.proconfig AS config,encode(sha256(convert_to(btrim(replace(p.prosrc,chr(13)||chr(10),chr(10)),chr(32)||chr(9)||chr(10)||chr(13)||chr(12)||chr(11)),'UTF8')),'hex') AS body_sha256 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace JOIN pg_language l ON l.oid=p.prolang WHERE n.nspname='public' AND p.proname=ANY($1::text[]) ORDER BY p.proname,arguments LIMIT 10001`,
      [names]
    )
  ).rows;
  if (
    [tables, columns, constraints, indexes, triggers, functions].some(
      (rows) => rows.length > 10_000
    )
  )
    throw new Error('Catalog capacity exceeded');
  return {
    tables: selected.filter((name) => tables.includes(name)).sort(),
    columns,
    constraints,
    indexes,
    triggers,
    functions,
  };
}
function compareSchema(expected, actual) {
  const issues = [];
  for (const category of ['tables', 'columns', 'constraints', 'indexes', 'triggers', 'functions']) {
    const key = (row) =>
      typeof row === 'string'
        ? row
        : [
            row.table_name ?? '',
            row.column_name ?? row.name + (category === 'functions' ? `(${row.arguments})` : ''),
          ].join('.');
    const observed = new Map(actual[category].map((row) => [key(row), canonical(row)]));
    if (observed.size !== actual[category].length)
      issues.push({ category, code: 'DUPLICATE_CATALOG_IDENTITIES' });
    for (const row of expected[category]) {
      const name = key(row);
      if (!observed.has(name)) issues.push({ category, entry: name, code: 'MISSING' });
      else if (observed.get(name) !== canonical(row))
        issues.push({ category, entry: name, code: 'DIFFERENT' });
      observed.delete(name);
    }
    if (observed.size) issues.push({ category, code: 'UNEXPECTED_ENTRIES', count: observed.size });
  }
  return issues;
}
module.exports = { canonical, sql, constraintsByMeaning, readSchemaCatalog, compareSchema, sha };
